// Regenerates hook/sources.g.dart and native/generated/Version.h from
// zxing-cpp's own CMake build, so that hook/build.dart compiles exactly the
// sources and defines upstream would.
//
// Run after updating third_party/zxing-cpp (needs cmake on PATH):
//   dart run tool/gen_sources.dart
import 'dart:convert';
import 'dart:io';

void main() {
  final String root = Directory.fromUri(
    Platform.script.resolve('..'),
  ).absolute.uri.toFilePath().replaceAll(RegExp(r'[/\\]$'), '');
  final String build = '$root/build/gen_sources';
  _run('cmake', <String>[
    '-S',
    '$root/native',
    '-B',
    build,
    '-DCMAKE_EXPORT_COMPILE_COMMANDS=ON',
    '-DFZX_WRITERS=ON',
  ]);

  final List<Map<String, dynamic>> units =
      (jsonDecode(File('$build/compile_commands.json').readAsStringSync())
              as List<dynamic>)
          .cast<Map<String, dynamic>>();
  final List<String> cpp = <String>[];
  final List<String> c = <String>[];
  final Set<String> cppDefines = <String>{};
  final Set<String> cDefines = <String>{};
  final RegExp define = RegExp(r'(?:^|\s)-D(\S+)');
  for (final Map<String, dynamic> unit in units) {
    final String file = File(unit['file'] as String).absolute.path;
    // Everything but native/fzx.cpp, which the hook builds on its own.
    if (!file.startsWith('$root/third_party/')) {
      continue;
    }
    final String relative = file.substring(root.length + 1);
    final String command =
        unit['command'] as String? ??
        (unit['arguments'] as List<dynamic>).join(' ');
    final Iterable<String> defines = define
        .allMatches(command)
        .map((RegExpMatch m) => m[1]!)
        .where((String d) => d != 'NDEBUG' && !d.endsWith('_EXPORTS'));
    if (relative.endsWith('.c')) {
      c.add(relative);
      cDefines.addAll(defines);
    } else {
      cpp.add(relative);
      cppDefines.addAll(defines);
    }
  }
  cpp.sort();
  c.sort();

  String list(String name, Iterable<String> values) =>
      'const List<String> $name = <String>[\n'
      '${values.map((String v) => "  '$v',\n").join()}];\n';
  File('$root/hook/sources.g.dart')
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(
      "// GENERATED by tool/gen_sources.dart from zxing-cpp's CMake build. "
      'Do not edit.\n\n'
      '${list('zxingCppSources', cpp)}\n'
      '${list('zxingCSources', c)}\n'
      '${list('zxingCppDefines', cppDefines.toList()..sort())}\n'
      '${list('zxingCDefines', cDefines.toList()..sort())}',
    );

  File('$root/native/generated/Version.h')
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(File('$build/zxing/Version.h').readAsStringSync());

  stdout.writeln(
    '${cpp.length} C++ and ${c.length} C sources; '
    'C++ defines $cppDefines, C defines $cDefines',
  );
}

void _run(String executable, List<String> arguments) {
  final ProcessResult result = Process.runSync(executable, arguments);
  if (result.exitCode != 0) {
    stderr
      ..write(result.stdout)
      ..write(result.stderr);
    exit(result.exitCode);
  }
}
