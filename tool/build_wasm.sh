#!/usr/bin/env bash
# Builds the WebAssembly engine into assets/web/:
#   fzx_reader.{js,wasm}  reading only, loaded first by every worker
#   fzx.{js,wasm}         reading and creation (zint), loaded on the first
#                         BarcodeWriter call
#
# The output is not committed (a new 2 MB binary in the history on every
# engine change): `make publish` and the web CI job build it, and so does
# anyone running the example on the web (`make wasm`). App developers get it
# prebuilt inside the published package.
#
# The JS files start with a hash of the sources (tool/wasm_sources_hash.sh);
# the build is skipped when it matches, unless --force is given.
#
# Emscripten is pinned (tool/wasm_config.sh). The script uses `emcc` from
# PATH if it is that version, otherwise the emsdk in $EMSDK, otherwise it
# installs one (about 1 GB) into ~/.cache/flutter_zxing/emsdk, outside the
# repository so that `flutter clean` does not remove it.
#
# usage: tool/build_wasm.sh [--force]
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$PWD"
source tool/wasm_config.sh

HASH="$(tool/wasm_sources_hash.sh)"
if [ "${1:-}" != "--force" ] && [ -f assets/web/fzx.wasm ] && [ -f assets/web/fzx_reader.wasm ] \
   && head -1 assets/web/fzx.js 2>/dev/null | grep -q "fzx-sources: $HASH " \
   && head -1 assets/web/fzx_reader.js 2>/dev/null | grep -q "fzx-sources: $HASH "; then
  echo "assets/web is up to date (fzx-sources: $HASH)"
  exit 0
fi

emcc_version() { emcc --version 2>/dev/null | head -1 | sed -E 's/.* ([0-9]+\.[0-9]+\.[0-9]+) .*/\1/'; }

if [ "$(emcc_version)" != "$FZX_EMSCRIPTEN_VERSION" ]; then
  EMSDK="${EMSDK:-${XDG_CACHE_HOME:-$HOME/.cache}/flutter_zxing/emsdk}"
  mkdir -p "$(dirname "$EMSDK")"
  if [ ! -x "$EMSDK/emsdk" ]; then
    git clone -q https://github.com/emscripten-core/emsdk.git "$EMSDK"
  fi
  if ! "$EMSDK/emsdk" list 2>/dev/null | grep -qE "^\s*$FZX_EMSCRIPTEN_VERSION\s+INSTALLED"; then
    "$EMSDK/emsdk" install "$FZX_EMSCRIPTEN_VERSION"
  fi
  "$EMSDK/emsdk" activate "$FZX_EMSCRIPTEN_VERSION" >/dev/null
  # shellcheck disable=SC1091
  source "$EMSDK/emsdk_env.sh" >/dev/null 2>&1
fi
[ "$(emcc_version)" = "$FZX_EMSCRIPTEN_VERSION" ] || { echo "error: need Emscripten $FZX_EMSCRIPTEN_VERSION, have $(emcc_version)" >&2; exit 1; }

JOBS="$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)"

build() { # <name> <FZX_WRITERS>
  local dir="build/wasm_$1"
  emcmake cmake -S native -B "$dir" -DCMAKE_BUILD_TYPE=Release -DFZX_WRITERS="$2" >/dev/null
  cmake --build "$dir" -j "$JOBS" >/dev/null
  cp "$dir/fzx.wasm" "assets/web/$1.wasm"
  # The module loads its .wasm next to itself; point it at the renamed file.
  { echo "// fzx-sources: $HASH (generated by tool/build_wasm.sh, do not edit)"
    sed "s/fzx\.wasm/$1.wasm/g" "$dir/fzx.js"; } > "assets/web/$1.js"
}

mkdir -p assets/web
build fzx_reader OFF
build fzx ON
ls -l assets/web/*.wasm
echo "fzx-sources: $HASH"
