// Regenerates lib/src/content/gs1_table.g.dart from zxing-cpp's GS1
// Application Identifier table (core/src/HRI.cpp), so that Gs1Content splits
// the data exactly where the engine's human readable text puts parentheses.
//
// Run after updating third_party/zxing-cpp:
//   make sources    (or: cd tool && dart run gen_gs1_table.dart)
import 'dart:io';

void main() {
  final String root = Directory.fromUri(
    Platform.script.resolve('..'),
  ).absolute.uri.toFilePath().replaceAll(RegExp(r'[/\\]$'), '');
  final String source = File(
    '$root/third_party/zxing-cpp/core/src/HRI.cpp',
  ).readAsStringSync();

  final int start = source.indexOf('static const AiInfo aiInfos[] = {');
  final int end = source.indexOf('};', start);
  if (start < 0 || end < 0) {
    throw StateError('aiInfos table not found in HRI.cpp');
  }
  final String table = source.substring(start, end);
  final RegExp entry = RegExp(r'\{\s*"(\d{2,4})",\s*(-?\d+)\s*\}');
  final List<RegExpMatch> entries = entry.allMatches(table).toList();
  if (entries.length < 100) {
    throw StateError('only ${entries.length} entries found in aiInfos');
  }
  final RegExpMatch? origin = RegExp(
    r'//\s*(https://github.com/gs1/gs1-syntax-dictionary[^\n]*)',
  ).firstMatch(source);

  final StringBuffer out = StringBuffer()
    ..writeln('// Generated by tool/gen_gs1_table.dart from zxing-cpp')
    ..writeln('// core/src/HRI.cpp. Do not edit.')
    ..writeln('//');
  if (origin != null) {
    out.writeln('// Source of the table: ${origin.group(1)}');
  }
  out
    ..writeln()
    ..writeln(
      '/// GS1 Application Identifier prefixes and the size of their data',
    )
    ..writeln(
      '/// field, in the order zxing-cpp looks them up. A negative size is a',
    )
    ..writeln('/// variable length field of at most that many characters.')
    ..writeln('const List<(String, int)> gs1FieldSizes = <(String, int)>[');
  for (final RegExpMatch m in entries) {
    out.writeln("  ('${m.group(1)}', ${m.group(2)}),");
  }
  out.writeln('];');

  final File target = File('$root/lib/src/content/gs1_table.g.dart');
  target.writeAsStringSync(out.toString());
  stdout.writeln('${target.path}: ${entries.length} Application Identifiers');
}
